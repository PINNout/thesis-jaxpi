"""
Generate the precision-ladder configs.

Run from a PDE's example folder (the one that contains configs/sota.py):

    python make_ladder.py burgers          # writes ladder/burgers_r0_fp32.py ...
    python make_ladder.py ks
    python make_ladder.py burgers --mantissa-base r2   # build m8/m6/m4 on rung 2
    python make_ladder.py ks --fmt e8m10 --acc-chunk 16    # ladder in another format
    python make_ladder.py ks --sweep e6m9 e7m8 e8m7        # one run per format
    python make_ladder.py ks --fmt e8m7 --mix fp8_e4m3 int8 # 8-bit weights, rest e8m7
    python make_ladder.py burgers --mx e4m3 e5m2 int8      # one MX run per element format

Every run uses the same small network, seed and batch 1024, so each rung is
compared against r0 from this same ladder (not against your older runs).
"""
import argparse, os

TRAINING = {
    "burgers": ['config.training.batch_size_per_device = 1024',
                'config.training.max_steps = 50000'],
    "adv":     ['config.training.batch_size_per_device = 1024',
                'config.training.max_steps = 50000'],
    "allen_cahn": ['config.training.batch_size_per_device = 1024',
                   'config.training.max_steps = 50000'],
    "ns_cyl":  ['config.training.batch_size_per_device = 1024',
                'config.training.max_steps = 50000'],
    "ks":      ['config.training.batch_size = 1024',
                'config.training.max_steps = 50000',
                'config.training.num_time_windows = 10',
                'config.training.windows_to_train = 1'],
    "ldc":     ['config.training.batch_size = 1024',
                'config.training.Re = [100, 400]',
                'config.training.max_steps = [25000, 25000]'],
}
SMOKE_STEPS = {"ldc": "[60, 60]"}
JET_PDES = ("ks",)          # Taylor mode: the accumulator loop must be unrolled

FWD = ("weights", "act_in", "act_out", "embed", "out_layer", "bias")


def rungs(pde, mbase, fmt="fp16", acc_chunk=None):
    """Ladder with `fmt` as the working format (default fp16)."""
    if pde in JET_PDES:
        acc_opts = {"acc_impl": "unroll", "acc_chunk": acc_chunk or 64}
    else:
        acc_opts = {"acc_impl": "scan", "acc_chunk": acc_chunk or 1}
    fwd = lambda f: {k: f for k in FWD}
    r2 = dict(fwd(fmt), ad="full")
    r3 = dict(r2, acc=fmt, **acc_opts)
    r4 = dict(r3, grads=fmt, residual=fmt)
    out = {
        "r0_fp32": {},
        "r1_fwd_ste": dict(fwd(fmt), ad="ste"),
        "r2_fwd_full": r2,
        "r3_acc": r3,
        "r4_grads_res": r4,
        "r5n_params_nearest": dict(r4, params=fmt, param_rounding="nearest"),
        "r5s_params_stoch": dict(r4, params=fmt, param_rounding="stochastic"),
    }
    if fmt == "fp16":
        out["x_e8m10"] = dict(fwd("e8m10"), ad="full")     # more exponent range
        for m in (8, 6, 4):                                # fewer mantissa bits
            f = f"e5m{m}"
            cfg = dict(fwd(f), ad="full")
            if mbase == "r3":
                cfg.update(acc=f, **acc_opts)
            out[f"m{m}_{mbase}"] = cfg
    else:
        out.pop("r0_fp32")                                 # already run
        out = {f"{fmt}_{k}": v for k, v in out.items()}
    return out


def mix(base, weight_formats):
    """Mixed precision: everything in `base` (values, derivatives, gradients),
    except the weights, whose stored values use a narrower format."""
    out = {}
    for w in weight_formats:
        cfg = dict({k: base for k in FWD}, ad="full")
        cfg["weights"] = w + ":ste"
        out[f"mix_{base}_w-{w}"] = cfg
    return out


def mx_sweep(elements, base="e6m9"):
    """One run per MX element format: every matmul operand in MX (blocks of 32),
    matmul results, activations, embedding and bias in `base`, derivatives included."""
    hooks = {"act_out": base, "embed": base, "bias": base, "ad": "full", "mx_out": base}
    return {f"s_mx_{e}": dict(hooks, mx=e) for e in elements}


def sweep(formats):
    """One run per format: all forward hooks in that format, ad=full."""
    return {f"s_{f}": dict({k: f for k in FWD}, ad="full") for f in formats}


TEMPLATE = '''"""Generated by make_ladder.py. Base: configs/sota.py. Run: {name}"""
import importlib.util, os
import ml_collections

_here = os.path.dirname(os.path.abspath(__file__))
_spec = importlib.util.spec_from_file_location("_base_cfg", os.path.join(_here, "..", "configs", "sota.py"))
_base = importlib.util.module_from_spec(_spec)
_spec.loader.exec_module(_base)


def get_config():
    config = _base.get_config()
    config.seed = int(os.environ.get("PI_SEED", 0))
    config.wandb.name = "{name}" + ("_s" + os.environ["PI_SEED"] if os.environ.get("PI_SEED") else "")

    # same small network and optimiser for every run (only precision varies)
    config.arch.num_layers = 4
    config.arch.hidden_dim = 128
    config.weighting.scheme = "grad_norm"
{training}

    config.precision = ml_collections.ConfigDict()
{precision}

    if os.environ.get("PI_SMOKE") or os.environ.get("PI_PROFILE"):
        smoke = bool(os.environ.get("PI_SMOKE"))
        config.wandb.name += "_smoke" if smoke else "_prof"
        config.training.max_steps = {smoke_steps}
        config.logging.log_every_steps = 40
        config.saving.save_every_steps = None
        if smoke:
            config.wandb.project = config.wandb.project + "-smoke"

    return config
'''

if __name__ == "__main__":
    ap = argparse.ArgumentParser()
    ap.add_argument("pde", choices=sorted(TRAINING))
    ap.add_argument("--out", default="ladder")
    ap.add_argument("--mantissa-base", choices=("r2", "r3"), default="r2")
    ap.add_argument("--fmt", default="fp16",
                    help="working format of the ladder, e.g. e8m10 (default fp16)")
    ap.add_argument("--acc-chunk", type=int, default=None,
                    help="products per accumulator rounding (default 1, or 64 for KS)")
    ap.add_argument("--sweep", nargs="+", metavar="FMT",
                    help="instead of a ladder: one all-values run per format, "
                         "e.g. --sweep e6m10 e7m10 e8m7")
    ap.add_argument("--mx", nargs="+", metavar="ELEM",
                    help="instead of a ladder: one MX run per element format, "
                         "e.g. --mx e4m3 e5m2 e2m3 e2m1 int8 (not for ks)")
    ap.add_argument("--mix", nargs="+", metavar="WFMT",
                    help="mixed precision: everything in --fmt, weights in each "
                         "of these narrower formats, e.g. --fmt e8m7 --mix fp8_e4m3 int8")
    a = ap.parse_args()
    os.makedirs(a.out, exist_ok=True)
    if a.mx and a.pde in JET_PDES:
        ap.error("MX runs use a custom backward pass, which Taylor mode (jet) used by "
                 f"{a.pde} cannot differentiate")
    if a.mx:
        todo = mx_sweep(a.mx)
    elif a.mix:
        todo = mix(a.fmt, a.mix)
    elif a.sweep:
        todo = sweep(a.sweep)
    else:
        todo = rungs(a.pde, a.mantissa_base, a.fmt, a.acc_chunk)
    for tag, prec in todo.items():
        name = f"{a.pde}_{tag}"
        lines = [f"    config.precision.{k} = {v!r}" for k, v in prec.items()] or ["    # all FP32"]
        src = TEMPLATE.format(
            name=name,
            training="\n".join("    " + t for t in TRAINING[a.pde]),
            precision="\n".join(lines),
            smoke_steps=SMOKE_STEPS.get(a.pde, "60"),
        )
        path = os.path.join(a.out, name + ".py")
        open(path, "w").write(src)
        print("wrote", path)
