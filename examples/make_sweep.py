"""
Generate one config per (equation, precision tag) for the weekly sweep.

Every generated file is a tiny wrapper: it loads the example's own
configs/sota.py and overrides only what is listed in EXAMPLES below, plus the
precision section. Run names are  <equation>_<tag>  (e.g. burgers_fp16).

Usage:   python3 make_sweep.py            # writes <example>/benchmark_configs/<eq>_<tag>.py
         python3 make_sweep.py --list     # just print the run names

Environment variables read by the generated configs:
  PI_SMOKE=1    tiny run (a few hundred steps, W&B name gets _smoke)
  PI_PROFILE=1  short run for profiling (see run_profiles.sh)
  PI_BATCH=N    override the batch size (to dodge out-of-memory without editing files)
"""
import os, sys

ROOT = os.environ.get("JAXPI_EXAMPLES", os.path.expanduser("~/thesis/jaxpi/examples"))

# ---- precision tags: (tag, format for all five components, native dtype) ----
TAGS = [
    ("fp32",        "fp32", None),    # baseline
    ("fp16",        "fp16", None),    # emulated (rounded, FP32 compute)
    ("bf16",        "bf16", None),
    ("int8",        "int8", None),
    ("fp16_native", "fp32", "fp16"),  # real FP16 compute on the GPU
    ("bf16_native", "fp32", "bf16"),  # real BF16 (FP32's range): used to tell range problems from precision problems.
                                      # Not in run_sweep.sh's default list; run it with TAGS=bf16_native
]

# ---- per-equation settings (what differs from the repo's sota.py) ----
# batch_key: name of the batch-size field in that example's config
# steps:     training steps (LDC: list, one entry per Reynolds number)
# Everything uses a 4 x 128 ModifiedMlp so only the precision changes between runs.
EXAMPLES = {
    #  folder               equation name   batch key                  batch  steps
    "adv":                 dict(eq="adv",        batch_key="batch_size_per_device", batch=8192, steps=50000),
    "burgers":             dict(eq="burgers",    batch_key="batch_size_per_device", batch=8192, steps=50000),
    "allen_cahn":          dict(eq="allen_cahn", batch_key="batch_size_per_device", batch=8192, steps=50000),
    "ks":                  dict(eq="ks",         batch_key="batch_size",            batch=4096, steps=50000, windows=10, train_windows=1),
    "ldc":                 dict(eq="ldc",        batch_key="batch_size",            batch=1024, steps=[25000, 25000], Re=[100, 400]),
    "ns_steady_cylinder":  dict(eq="ns_cyl",     batch_key="batch_size_per_device", batch=1024, steps=50000),
}
LAYERS, HIDDEN = 4, 128
SEED = 0

TEMPLATE = '''"""Generated by make_sweep.py. Base: configs/sota.py. Run: {name}"""
import importlib.util, os
import ml_collections

_here = os.path.dirname(os.path.abspath(__file__))
_spec = importlib.util.spec_from_file_location("_base_cfg", os.path.join(_here, "..", "configs", "sota.py"))
_base = importlib.util.module_from_spec(_spec)
_spec.loader.exec_module(_base)


def get_config():
    config = _base.get_config()
    config.seed = {seed}
    config.wandb.name = "{name}"

    # same small network and optimiser for every run (only precision varies)
    config.arch.num_layers = {layers}
    config.arch.hidden_dim = {hidden}
    config.weighting.scheme = "grad_norm"      # NTK weighting does not fit in 8 GB
    config.training.{batch_key} = {batch}
    if os.environ.get("PI_BATCH"):            # e.g. PI_BATCH=1024 if a run runs out of memory
        config.training.{batch_key} = int(os.environ["PI_BATCH"])
{extra}
    config.precision = ml_collections.ConfigDict()
    config.precision.weights = "{fmt}"
    config.precision.act_in = "{fmt}"
    config.precision.act_out = "{fmt}"
    config.precision.embed = "{fmt}"
    config.precision.out_layer = "{fmt}"
    config.precision.native = {native}

    if os.environ.get("PI_SMOKE") or os.environ.get("PI_PROFILE"):
        smoke = bool(os.environ.get("PI_SMOKE"))
        config.wandb.name += "_smoke" if smoke else "_prof"
        config.training.max_steps = {short}
        config.logging.log_every_steps = {log_every}
        config.saving.save_every_steps = None
        if smoke:
            config.wandb.project = config.wandb.project + "-smoke"
{short_extra}
    return config
'''


def build(folder, spec, tag, fmt, native):
    name = f"{spec['eq']}_{tag}"
    steps = spec["steps"]
    extra, short_extra = "", ""
    if isinstance(steps, list):  # LDC curriculum
        extra += f"    config.training.Re = {spec['Re']}\n    config.training.max_steps = {steps}\n"
        short = str([60] * len(steps))
    else:
        extra += f"    config.training.max_steps = {steps}\n"
        short = "60"
    if "windows" in spec:        # KS: keep the repo's 10 windows (each = 1/10 of the time domain) ...
        extra += f"    config.training.num_time_windows = {spec['windows']}\n"
        # ... but only train the first one (needs the small patch_train.py edit of ks/train.py)
        extra += f"    config.training.windows_to_train = {spec['train_windows']}\n"
    log_every = "40"
    return name, TEMPLATE.format(
        name=name, seed=SEED, layers=LAYERS, hidden=HIDDEN, batch_key=spec["batch_key"],
        batch=spec["batch"], extra=extra, fmt=fmt, native=repr(native), short=short,
        log_every=log_every, short_extra=short_extra)


if __name__ == "__main__":
    only_list = "--list" in sys.argv
    for folder, spec in EXAMPLES.items():
        out_dir = os.path.join(ROOT, folder, "benchmark_configs")
        if not only_list:
            if not os.path.isdir(os.path.join(ROOT, folder)):
                print(f"{folder}: example folder not found, skipped"); continue
            os.makedirs(out_dir, exist_ok=True)
        for tag, fmt, native in TAGS:
            name, text = build(folder, spec, tag, fmt, native)
            if only_list:
                print(f"{folder} {name}"); continue
            path = os.path.join(out_dir, name + ".py")
            with open(path, "w") as f:
                f.write(text)
            print("wrote", os.path.relpath(path, ROOT))
