"""
Generate Navier-Stokes benchmark configs (one seed, several precisions).

Instead of copying a template with sed, each generated file is a tiny wrapper
that loads the example's own configs/<BASE> and overrides only the seed, the
step budget, the W&B name and the precision section. Everything else (network,
optimizer, loss weighting, batch size) stays exactly as the repo defines it.

Usage (from anywhere):   python3 make_ns.py
Edit the block below first.
"""
import os

# ===== EDIT THESE =====
EXAMPLE = "ns_steady_cylinder"
BASE = "sota.py"
SEED = 0
STEPS = 50000          # None = keep the repo default
BATCH = 1024
HIDDEN = 128        # None = keep repo default (256)
E = "fp8_e4m3"
#         tag              weights  act_in   act_out  embed    out_layer
CONFIGS = [
    ("fp32",               "fp32",  "fp32",  "fp32",  "fp32",  "fp32"),
    ("fp16_wa",            "fp16",  "fp16",  "fp32",  "fp32",  "fp32"),
    ("fp16all",            "fp16",  "fp16",  "fp16",  "fp16",  "fp16"),
    ("bf16_wa",            "bf16",  "bf16",  "fp32",  "fp32",  "fp32"),
    ("fp8e4m3_wa",         E,       E,       "fp32",  "fp32",  "fp32"),
    ("int8_wa",            "int8",  "int8",  "fp32",  "fp32",  "fp32"),
    ("fp8e4m3_all",        E,       E,       E,       E,       E),
]
# =======================

TEMPLATE = '''"""Generated by make_ns.py. Base: configs/{base}. Precision tag: {tag}."""
import importlib.util
import os

import ml_collections

_here = os.path.dirname(os.path.abspath(__file__))
_spec = importlib.util.spec_from_file_location(
    "_base_cfg", os.path.join(_here, "..", "configs", "{base}")
)
_base = importlib.util.module_from_spec(_spec)
_spec.loader.exec_module(_base)


def get_config():
    config = _base.get_config()

    # Per-run settings (the only things changed relative to the repo config)
    config.seed = {seed}
{steps_line}{batch_line}{hidden_line}
    config.wandb.name = "{example}_%dx%d_{tag}_s{seed}" % (
        config.arch.num_layers,
        config.arch.hidden_dim,
    )

    config.precision = ml_collections.ConfigDict()
    config.precision.weights = "{w}"
    config.precision.act_in = "{ai}"
    config.precision.act_out = "{ao}"
    config.precision.embed = "{em}"
    config.precision.out_layer = "{ol}"

    return config
'''

home = os.path.expanduser("~/thesis/jaxpi/examples")
out_dir = os.path.join(home, EXAMPLE, "benchmark_configs")
base_path = os.path.join(home, EXAMPLE, "configs", BASE)
if not os.path.isfile(base_path):
    raise SystemExit(f"Base config not found: {base_path}\nCheck EXAMPLE and BASE (ls {home}).")
os.makedirs(out_dir, exist_ok=True)

steps_line = f"    config.training.max_steps = {STEPS}\n" if STEPS else ""
batch_line = f"    config.training.batch_size_per_device = {BATCH}\n" if BATCH else ""
hidden_line = f"    config.arch.hidden_dim = {HIDDEN}\n" if HIDDEN else ""

for tag, w, ai, ao, em, ol in CONFIGS:
    name = f"{EXAMPLE}_{tag}_s{SEED}"
    path = os.path.join(out_dir, name + ".py")
    if os.path.exists(path):
        print("exists:  ", name)
        continue
    with open(path, "w") as f:
        f.write(TEMPLATE.format(
            base=BASE, tag=tag, seed=SEED, example=EXAMPLE,
            steps_line=steps_line, batch_line=batch_line, hidden_line=hidden_line,
            w=w, ai=ai, ao=ao, em=em, ol=ol,
        ))
    print("created: ", name)

print(f"\nConfigs are in {out_dir}")
print("Next: check the repo settings you are inheriting:")
print(f"  grep -n 'arch_name\\|num_layers\\|hidden_dim\\|scheme\\|batch_size\\|max_steps' {base_path}")
